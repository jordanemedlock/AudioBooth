#!/usr/bin/env bash
# Generates AudioBooth/Local.xcconfig for CI (gitignored locally; never committed).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${ROOT}/AudioBooth/Local.xcconfig"

ORG_IDENTIFIER="${ORG_IDENTIFIER:-com.jordanemedlock.audiobooth.ci}"
DEVELOPMENT_TEAM="${DEVELOPMENT_TEAM:-}"

{
  echo "// Generated by scripts/ci/generate-local-xcconfig.sh — CI only."
  if [ -n "$DEVELOPMENT_TEAM" ]; then
    echo "DEVELOPMENT_TEAM = ${DEVELOPMENT_TEAM}"
  fi
  echo "ORG_IDENTIFIER = ${ORG_IDENTIFIER}"
  echo "SWIFT_ACTIVE_COMPILATION_CONDITIONS = \$(inherited) CONTRIBUTOR_BUILD"
} >"$OUT"

echo "Wrote ${OUT}"
